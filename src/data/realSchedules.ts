/**
 * Generates official schedules for a specific date (YYYY-MM-DD).
 */
export function generateSchedulesForDate(dateStr: string): Schedule[] {
  return REAL_SCHEDULE_TEMPLATES.map((tpl) => {
    // Deterministic seat booking fill for realistic inventory
    const pseudoHash = tpl.templateId.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
    const dayOffset = Number(dateStr.replace(/-/g, "")) % 30;
    const booked = Math.floor(((pseudoHash + dayOffset) % 70) * (tpl.totalSeats / 100));
    const available = Math.max(12, tpl.totalSeats - booked);

    return {
      id: `${tpl.templateId}-${dateStr}`,
      route_name: tpl.routeName,
      origin: tpl.origin,
      destination: tpl.destination,
      departure_date: dateStr,
      departure_time: `${tpl.departureTime}:00`,
      arrival_time: `${tpl.arrivalTime}:00`,
      vehicle_name: tpl.vehicleName,
      vehicle_number: tpl.vehicleNumber,
      total_seats: tpl.totalSeats,
      available_seats: available,
      price: tpl.price,
      status: "scheduled",
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
    };
  });
}

/**
 * Generates rolling schedules for the next 14 calendar days.
 */
export function getRollingMaritimeSchedules(daysAhead = 14): Schedule[] {
  const result: Schedule[] = [];
  const today = new Date();

  for (let i = 0; i < daysAhead; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() + i);
    const dateStr = d.toISOString().split("T")[0];
    result.push(...generateSchedulesForDate(dateStr));
  }

  return result;
}
